-- =============================================================================================
-- MJ Forms v1.1.x — re-enable SaveReturnMode = datestamps_only on FormAutomationRun & FormResponseAnswer
-- =============================================================================================
-- SUPERSEDES the full-row spCreate/spUpdate definitions restored in V202610201910 (#320 / #315)
-- while MJ Forms was still pinned to MJ 6.1 LTS. Now that MJ Forms targets MJ 6.2
-- (mjVersionRange >=6.2.0-edge.8 <7.0.0, overrides 6.2.1 — all containing MJ commit f033cb970b /
-- MJ#5804), both SQLServerDataProvider and PostgreSQLDataProvider support SaveReturnMode =
-- datestamps_only natively.
--
-- WHY THE ENTITY METADATA UPDATE LANDS ATOMICALLY WITH THE STORED PROCEDURES:
--   1. No host running migrations-only upgrades ever executes a 3-column datestamps_only sproc
--      while Entity.Configuration is NULL (SaveReturnMode = full) or TrackRecordChanges = 1,
--      preventing SQL Server error 213 and preventing BaseEntity from overwriting in-memory fields.
--   2. Host-truth CodeGen convergence (host-truth-gate.yml, MJ 6.2.1) sees Entity.SaveReturnMode
--      = datestamps_only and matching 3-column sprocs in one pass, so mj codegen emits zero diff.
--   3. metadata/entities/.save-return-datestamps-only.json declares the identical values so the
--      next release Metadata_Sync push stays converged with zero drift.
--
-- ENTITIES COVERED (2):
--   - MJ_BizApps_Forms: Form Automation Runs ([FormAutomationRun]):
--     spCreateFormAutomationRun, spUpdateFormAutomationRun (preserving @FormAutomationEventID)
--   - MJ_BizApps_Forms: Form Response Answers ([FormResponseAnswer]):
--     spCreateFormResponseAnswer, spUpdateFormResponseAnswer
-- =============================================================================================

UPDATE [${mjSchema}].[Entity]
SET
    [TrackRecordChanges] = 0,
    [Configuration] = CASE
        WHEN NULLIF(LTRIM(RTRIM(COALESCE([Configuration], N''))), N'') IS NULL
            THEN N'{
  "SaveReturnMode": "datestamps_only"
}'
        ELSE JSON_MODIFY([Configuration], '$.SaveReturnMode', 'datestamps_only')
    END
WHERE [SchemaName] = '${flyway:defaultSchema}'
  AND [BaseTable] IN ('FormAutomationRun', 'FormResponseAnswer');
GO




















































