-- =================================================================================================
-- Reusable form templates
-- =================================================================================================
-- WHAT WAS MISSING. Forms shipped five starter templates hardcoded in TypeScript
-- (packages/Actions/src/custom/templates/starter-templates.ts) and no way for an author to add
-- one of their own. Someone who builds a good intake form and wants the next department to start
-- from it has to rebuild it by hand.
--
-- A TEMPLATE IS A FORM. This column, rather than a FormTemplate table holding a serialized
-- blueprint. The blueprint shape (form-blueprint.ts) carries name/renderMode/pages/questions/
-- options and NOTHING else — no ConditionalRule, no ValidationRule, no ScoringConfig, no
-- FormScreen, no StyleID, no FormAutomation, no FormEntityBinding. So "save this form as a
-- template" through a blueprint would silently discard the branching, the theme, the welcome and
-- thank-you screens and the automations: precisely the work that makes a form worth reusing, lost
-- with no error. Marking the Form itself is lossless by construction, needs no second
-- serialization format to keep in step with the schema, and means a template can be opened and
-- edited in the existing builder with no new UI at all.
--
-- The starters stay in code and are NOT seeded as rows here. A seeded starter would be deletable,
-- and one author deleting "Contact form" would delete it for everyone on the host.
--
-- WHY THE CHECK CONSTRAINT IS THE LOAD-BEARING HALF. Forms are never deleted — every child table
-- holds a plain FK to Form(ID) with no ON DELETE CASCADE, and a form that collected responses
-- must not lose them — which is why the home list archives (Status='Closed') instead. Templates
-- ARE deletable, and the only thing that makes that safe is that a template can never have
-- collected a response. That is not a convention anyone can be relied on to uphold in application
-- code; it is this constraint. A template cannot be Published, an unpublished form has no
-- published FormVersion, and the public submit endpoint resolves a distribution to a published
-- version — so no submission path can reach one.
-- =================================================================================================

ALTER TABLE [${flyway:defaultSchema}].[Form] ADD
    IsTemplate BIT NOT NULL CONSTRAINT DF_Form_IsTemplate DEFAULT 0;
GO

EXEC sp_addextendedproperty @name = N'MS_Description', @value = N'When 1 this Form is a reusable template rather than a live form: it is hidden from the forms list, cannot be published or distributed, and is offered in the template gallery as a starting point. Creating a form from a template deep-copies it, so the two are independent afterwards. Templates are the only forms that may be deleted, which is safe precisely because CK_Form_TemplateNotPublished stops one ever collecting a response',
    @level0type = N'SCHEMA', @level0name = N'${flyway:defaultSchema}', @level1type = N'TABLE', @level1name = N'Form', @level2type = N'COLUMN', @level2name = N'IsTemplate';
