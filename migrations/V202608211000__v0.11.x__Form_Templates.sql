-- A template may not be Published. This is what makes template deletion safe (see the header):
-- no published version means no distribution can resolve to it, so no response can ever exist.
ALTER TABLE [${flyway:defaultSchema}].[Form] WITH CHECK ADD CONSTRAINT CK_Form_TemplateNotPublished
    CHECK (IsTemplate = 0 OR Status <> 'Published');
GO

